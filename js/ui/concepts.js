  C.conceptQuiz = function (step) {
    const list = C.CONCEPTS[step];
    if (!list) return null;
    const S = C.S;
    const ans = () => (S.quiz = S.quiz || {});
    const box = h('section', { class: 'concept-quiz' });
    function draw() {
      box.innerHTML = '';
      const A = ans();
      const done = list.filter((_, i) => A[step + '-' + i] !== undefined);
      const right = done.filter((q) => A[step + '-' + list.indexOf(q)] === q.a).length;
      box.append(h('div', { class: 'cq-head' },
        h('h3', null, '개념 확인 퀴즈'),
        h('span', { class: 'tag' + (done.length === list.length ? ' ok' : '') }, done.length === list.length ? right + ' / ' + list.length + ' 맞힘' : done.length + ' / ' + list.length + ' 풀었어요')));
      list.forEach((item, i) => {
        const key = step + '-' + i, pick = A[key];
        const answered = pick !== undefined;
        const ord = item.fixed ? [0, 1, 2, 3, 4] : C.rng(C.hashStr('cq#' + key)).shuffle([0, 1, 2, 3, 4]);
        box.append(h('div', { class: 'cq-item' },
          h('p', { class: 'cq-q' }, h('b', null, (i + 1) + '. '), item.q),
          h('div', { class: 'cq-opts' }, ord.map((k, pos) => h('button', {
            class: 'cq-opt' + (answered ? (k === item.a ? ' right' : k === pick ? ' wrong' : ' dim') : ''),
            disabled: answered,
            onclick: () => { A[key] = k; C.save(); draw(); }
          }, h('span', { class: 'n' }, NUM[pos]), h('span', null, item.o[k])))),
          answered ? h('div', { class: 'callout ' + (pick === item.a ? 'good' : 'warn') },
            h('b', null, pick === item.a ? '맞아요! ' : '아쉬워요. 정답은 ' + NUM[ord.indexOf(item.a)] + '. '), item.e) : null));
      });
      if (done.length) box.append(h('div', { class: 'row', style: { justifyContent: 'flex-end' } },
        h('button', { class: 'sm', onclick: () => { list.forEach((_, i) => delete A[step + '-' + i]); C.save(); draw(); } }, '다시 풀어 보기')));
    }
    draw();
    return box;
  };

  // 내 기록용: 모든 단계 퀴즈의 맞힌 수
  C.conceptScore = function () {
    const A = C.S.quiz || {};
    let n = 0, right = 0, done = 0;
    Object.keys(C.CONCEPTS).forEach((s) => C.CONCEPTS[s].forEach((q, i) => { n++; const p = A[s + '-' + i]; if (p !== undefined) { done++; if (p === q.a) right++; } }));
    return { n, right, done };
  };
